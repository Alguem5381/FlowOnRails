using System.Collections.Generic;
using System.Text;

using FlowOnRails.Analysis.Internal;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace FlowOnRails.Analyzers;

[Generator(LanguageNames.CSharp)]
public sealed class ErrorFlowGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var methods = context.SyntaxProvider.CreateSyntaxProvider(
            static (node, _) => node is MethodDeclarationSyntax or PropertyDeclarationSyntax or IndexerDeclarationSyntax,
            static (syntaxContext, cancellationToken) =>
                syntaxContext.SemanticModel.GetDeclaredSymbol(syntaxContext.Node, cancellationToken) switch
                {
                    IMethodSymbol method => method,
                    IPropertySymbol property => property.GetMethod,
                    _ => null
                }
        ).Collect();
        var inputs = context.CompilationProvider.Combine(context.AnalyzerConfigOptionsProvider).Combine(methods);

        context.RegisterSourceOutput(inputs, static (productionContext, input) =>
        {
            var ((compilation, options), declaredMethods) = input;

            if (!options.GlobalOptions.TryGetValue("build_property.FlowOnRailsEnableFlowAnalysis", out var enabled)
                || !string.Equals(enabled, "true", System.StringComparison.OrdinalIgnoreCase))
                return;

            var symbols = LibrarySymbols.Create(compilation);

            if (symbols is null || compilation.GetTypeByMetadataName("FlowOnRails.FlowAnalysisSummaryAttribute") is null)
                return;

            var bodies = new MethodBodyResolver(compilation);
            var seenMethods = new HashSet<IMethodSymbol>(SymbolEqualityComparer.Default);
            var seenMethodIds = new HashSet<string>(System.StringComparer.Ordinal);
            var source = new StringBuilder("// <auto-generated/>\n#nullable enable\n");
            var metadataCount = 0;

            foreach (var method in declaredMethods)
            {
                productionContext.CancellationToken.ThrowIfCancellationRequested();

                if (method is null
                    || method.MethodKind is not (MethodKind.Ordinary or MethodKind.PropertyGet)
                    || method.ContainingType.TypeKind == TypeKind.Interface
                    || method.IsAbstract
                    || !(symbols.IsTrackedReturn(method.ReturnType)
                        || method.ReturnType.SpecialType == SpecialType.System_Boolean
                        || System.Linq.Enumerable.Any(method.Parameters, parameter => parameter.RefKind is RefKind.Ref or RefKind.Out))
                    || !seenMethods.Add(method.OriginalDefinition))
                    continue;

                var methodId = DocumentationCommentId.CreateDeclarationId(method.OriginalDefinition);
                var graph = bodies.GetGraph(method, productionContext.CancellationToken);

                if (methodId is null || graph is null || !seenMethodIds.Add(methodId))
                    continue;

                var bodyMethod = method.PartialImplementationPart ?? method;
                var summary = SummaryBuilder.Analyze(symbols, bodies, graph, bodyMethod, productionContext.CancellationToken);
                var payload = SummaryCodec.Encode(summary, bodyMethod);
                source.Append("[assembly: global::FlowOnRails.FlowAnalysisSummaryAttribute(")
                    .Append(SummaryCodec.SchemaVersion).Append(", ")
                    .Append(Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(methodId, true)).Append(", ")
                    .Append(Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(payload, true)).Append(")]\n");
                metadataCount++;
            }

            if (metadataCount > 0)
                productionContext.AddSource("FlowOnRails.ErrorSummaries.g.cs", SourceText.From(source.ToString(), Encoding.UTF8));
        });
    }
}
